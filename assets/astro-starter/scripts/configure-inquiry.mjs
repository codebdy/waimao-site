import { readFile, writeFile, mkdir, unlink } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { pathToFileURL } from 'node:url';
import { resolveDeployment } from '../config/deployment.mjs';

const marker = '// Generated by export-site configure-inquiry; edit the shared handler instead.\n';
export function inquiryFiles(settings, env = {}) {
  const { target } = resolveDeployment(settings, env);
  const files = { 'api/inquiry.js': null, 'functions/api/inquiry.js': null, 'public/_routes.json': null };
  if (settings.inquiry?.provider !== 'rxcms') return files;
  if (target === 'vercel') files['api/inquiry.js'] = marker + "import { handleInquiry } from '../src/lib/inquiry.mjs';\nexport default { fetch(request) { return handleInquiry(request, process.env); } };\n";
  else {
    files['functions/api/inquiry.js'] = marker + "import { handleInquiry } from '../../src/lib/inquiry.mjs';\nexport function onRequest(context) { return handleInquiry(context.request, context.env); }\n";
    files['public/_routes.json'] = JSON.stringify({ version: 1, description: 'Generated by export-site configure-inquiry', include: ['/api/inquiry'], exclude: [] }, null, 2) + '\n';
  }
  return files;
}

function isGenerated(name, text) {
  if (text.startsWith(marker)) return true;
  if (name !== 'public/_routes.json') return false;
  try { return JSON.parse(text).description === 'Generated by export-site configure-inquiry'; } catch { return false; }
}

export async function configureInquiry(root, settings, env = {}, check = false) {
  const planned = inquiryFiles(settings, env), current = {};
  // Inspect every target before writing anything. Never overwrite or delete a user-owned endpoint/routing file.
  for (const [name, expected] of Object.entries(planned)) {
    let actual = null;
    try { actual = await readFile(resolve(root, name), 'utf8'); } catch (e) { if (e.code !== 'ENOENT') throw e; }
    current[name] = actual;
    if (actual !== null && actual !== expected && !isGenerated(name, actual)) {
      // Nothing to generate here: a user's own file (e.g. other Pages Functions routes) is left untouched.
      if (expected === null) { current[name] = null; continue; }
      throw new Error(`Refusing to change user-owned ${name}; integrate the inquiry route manually.`);
    }
    if (check && actual !== expected) throw new Error('Inquiry configuration changed: run npm run configure:inquiry locally and commit the generated changes before deployment.');
  }
  if (check) return;
  for (const [name, expected] of Object.entries(planned)) {
    const path = resolve(root, name);
    if (expected === null) { if (current[name] !== null) await unlink(path); }
    else { await mkdir(dirname(path), { recursive: true }); await writeFile(path, expected); }
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const root = resolve(import.meta.dirname, '..');
  const { default: settings } = await import(pathToFileURL(resolve(root, 'site.config.mjs')).href);
  await configureInquiry(root, settings, process.env, process.argv.includes('--check'));
}
