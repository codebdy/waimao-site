// Generates platform 301 rules from config/redirects.mjs: public/_redirects (Cloudflare) and the
// "redirects" list of vercel.json (Vercel). Both are committed, because Vercel reads vercel.json before building.
// `--check` (run by prebuild) fails when the committed files are out of date.
import { readFile, writeFile, unlink } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const marker = '# Generated by waimao-site configure-redirects from config/redirects.mjs; edit that file instead.';

export function validateRedirects(map) {
  const entries = Object.entries(map ?? {});
  const bad = value => typeof value !== 'string' || !value.startsWith('/') || value.startsWith('//') || /[\s?#*:]/.test(value);
  for (const [from, to] of entries) {
    if (bad(from) || from === '/' || from.endsWith('/') || from !== from.toLowerCase()) {
      throw new Error(`Redirect source ${JSON.stringify(from)} must be a lowercase path without trailing slash, query or wildcard.`);
    }
    // Page targets only: the build checks each one is a generated page, so a rule can never 301 to a 404.
    if (bad(to) || !to.endsWith('/')) throw new Error(`Redirect target ${JSON.stringify(to)} must be a same-site page path ending in "/".`);
    const target = to.replace(/\/$/, '').toLowerCase();
    if (target === from) throw new Error(`Redirect ${from} points to itself.`);
    if (Object.hasOwn(map, target)) throw new Error(`Redirect ${from} → ${to} chains into another redirect; point it at the final address.`);
  }
  return entries;
}

export function redirectFiles(map, vercelJson) {
  const entries = validateRedirects(map);
  const pairs = entries.flatMap(([from, to]) => [[from, to], [`${from}/`, to]]);
  const cloudflare = entries.length ? `${marker}\n${pairs.map(([from, to]) => `${from} ${to} 301`).join('\n')}\n` : null;
  // No rules and no generated list: leave an existing vercel.json byte-for-byte alone (undefined = unchanged).
  if (!entries.length && !Object.hasOwn(vercelJson ?? {}, 'redirects')) return { 'public/_redirects': cloudflare, 'vercel.json': undefined };
  const vercel = { ...(vercelJson ?? {}) };
  if (entries.length) vercel.redirects = pairs.map(([source, destination]) => ({ source, destination, statusCode: 301 }));
  else delete vercel.redirects;
  const vercelText = Object.keys(vercel).length ? JSON.stringify(vercel, null, 2) + '\n' : null;
  return { 'public/_redirects': cloudflare, 'vercel.json': vercelText };
}

async function readOptional(path) {
  try { return await readFile(path, 'utf8'); } catch (e) { if (e.code === 'ENOENT') return null; throw e; }
}

export async function configureRedirects(root, map, check = false) {
  const redirectsPath = resolve(root, 'public/_redirects'), vercelPath = resolve(root, 'vercel.json');
  const current = { 'public/_redirects': await readOptional(redirectsPath), 'vercel.json': await readOptional(vercelPath) };
  // Never take over a hand-written Cloudflare _redirects file.
  if (current['public/_redirects'] !== null && !current['public/_redirects'].startsWith(marker)) {
    throw new Error('public/_redirects was not generated by configure-redirects; move its rules into config/redirects.mjs first.');
  }
  let vercelJson = null;
  if (current['vercel.json'] !== null) {
    try { vercelJson = JSON.parse(current['vercel.json']); } catch { throw new Error('vercel.json is not valid JSON.'); }
  }
  const planned = redirectFiles(map, vercelJson);
  for (const [name, expected] of Object.entries(planned)) {
    if (expected === undefined || current[name] === expected) continue;
    if (check) throw new Error('Redirect rules changed: run npm run configure:redirects locally and commit public/_redirects and vercel.json before deployment.');
    const path = resolve(root, name);
    if (expected === null) await unlink(path);
    else await writeFile(path, expected);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const root = resolve(import.meta.dirname, '..');
  const { default: map } = await import(pathToFileURL(resolve(root, 'config/redirects.mjs')).href);
  await configureRedirects(root, map, process.argv.includes('--check'));
}
